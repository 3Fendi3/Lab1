# A
a = 1+2
print("a", a, type(a)) # dodawanie

b = 1+4.5
print("b", b, type(b)) # dodawanie liczby calkowitej z liczbą zmiennoprzecinkowa

c = 3/2
print("c", c, type(c)) # dzielenie z wynikiem z liczbą zmiennoprzecinkowa

d = 4/2
print("d", d, type(d)) # dzielenie z wynikiem z liczbą zmiennoprzecinkowa
e = 3//2
print("e", e, type(e)) # dzielenie z wynikiem z liczbą calkowita

f = -3//2
print("f", f, type(f)) # dzielenie z wynikiem z liczba calkowita

g = 11%2
print("g", g, type(g)) # reszta z dzielenia czyli modulo

h = 2**10
print("h", h, type(h)) # potegowanie

i = 8**(1/3)
print("i", i, type(i)) # pierwiastek 3ciego stopnia, czyli potęgowanie przez ulamek



#B
a = int(3.0)
print("a", a, type(a)) # sprawia ze float staje sie int

b = float(3)
print("b", b, type(b)) # zamienia int na float

c = float("3")
print("c", c, type(c)) # zamienia tekst na float

d = str(12.4)
print("d", d, type(d)) # zamiana liczby na tekst

e = bool(0)
print("e", e, type(e)) # zamiana liczby na fałsz
